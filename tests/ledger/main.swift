import Foundation
let record = TaskRecord(id: "t1", state: "running", verified: false, owner: "operations", parentID: "parent", createdAt: "2026-11-10T00:00:00Z", updatedAt: "2026-11-10T00:00:00Z", resultSummary: "", title: "Inspect the source")
let data = try TaskLedger.encode([record])
let decoded = try TaskLedger.decode(data)
assert(decoded == [record])
let stopped = TaskLedger.interruptRunning(decoded, at: "2026-11-10T01:00:00Z")
assert(stopped[0].state == "failed")
assert(stopped[0].verified == false)
assert(stopped[0].resultSummary == "interrupted")
assert(stopped[0].updatedAt == "2026-11-10T01:00:00Z")
assert(stopped[0].parentID == "parent")
let finished = TaskRecord(id: "t2", state: "completed", verified: true, owner: "operations", parentID: nil, createdAt: "2026-11-10T00:00:00Z", updatedAt: "2026-11-10T00:10:00Z", resultSummary: "done", title: "Done")
assert(TaskLedger.interruptRunning([finished], at: "2026-11-10T02:00:00Z") == [finished])
let junk = Data("{\"state\":\"nope\"}".utf8)
assert(try TaskLedger.decode(junk).isEmpty)
let parent = TaskRecord(id: "parent", state: "running", verified: false, owner: "operations", parentID: nil, createdAt: "2026-11-10T00:00:00Z", updatedAt: "2026-11-10T00:00:00Z", resultSummary: "", title: "Inspect the source")
let manager = TaskRecord(id: "manager", state: "failed", verified: false, owner: "operations-manager", parentID: parent.id, createdAt: "2026-11-10T00:00:00Z", updatedAt: "2026-11-10T00:00:00Z", resultSummary: "manager model not configured", title: "Operations manager")
let worker = TaskRecord(id: "worker", state: "running", verified: false, owner: "gpt-6-astra", parentID: parent.id, createdAt: "2026-11-10T00:00:00Z", updatedAt: "2026-11-10T00:00:00Z", resultSummary: "", title: "Workspace worker")
assert(parent.owner != "jarvis")
assert(manager.parentID == parent.id && worker.parentID == parent.id)
assert(manager.resultSummary == "manager model not configured")
let hierarchy = try TaskLedger.decode(try TaskLedger.encode([parent, manager, worker]))
assert(hierarchy.count == 3)
assert(hierarchy[1].parentID == hierarchy[0].id)
let interrupted = TaskLedger.interruptRunning(hierarchy, at: "2026-11-10T03:00:00Z")
assert(interrupted[0].state == "failed" && interrupted[0].resultSummary == "interrupted")
assert(interrupted[2].state == "failed" && interrupted[2].parentID == "parent")
assert(interrupted[1].state == "failed" && interrupted[1].resultSummary == "manager model not configured")
print("PASS: task ledger round-trips, and a running task relaunch is interrupted")
print("PASS: director work keeps a parent id, and Jarvis is not the owner")
