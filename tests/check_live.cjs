const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
let JSDOM;
try { ({JSDOM}=require('jsdom')); } catch { ({JSDOM}=require('../.build/test-deps/node_modules/jsdom')); }
const root = path.resolve(__dirname, '..');
const dom = new JSDOM(fs.readFileSync(path.join(root, 'Resources/index.html'), 'utf8'), { url: 'https://jarvis.test/', runScripts: 'outside-only' });
const w = dom.window, d = w.document, calls = [];
w.JARVIS_MODE = 'workspace';
w.requestAnimationFrame = () => 0;
w.ResizeObserver = class { observe() {} };
w.HTMLCanvasElement.prototype.getContext = () => ({});
w.webkit = { messageHandlers: { jarvis: { postMessage: value => calls.push(value) } } };
// Classic <script> tags share one global scope; one eval of both files does the same here.
w.eval(fs.readFileSync(path.join(root, 'Resources/app.js'), 'utf8') + '\n;\n' + fs.readFileSync(path.join(root, 'Resources/live.js'), 'utf8'));
assert.ok(w.JarvisLive, 'live.js loaded');
const now = Date.now();
const tasks = [
  {id:'P1', state:'running', verified:false, owner:'creative', title:'Create a thirty-second video about Drop Assassin', createdAt:'', updatedAt:'', resultSummary:''},
  {id:'R1', parentID:'P1', state:'running', verified:false, owner:'creative · video', title:'Create a thirty-second video about Drop Assassin', createdAt:'', updatedAt:'', resultSummary:'Rendering 2 shots'},
  {id:'P0', state:'completed', verified:false, owner:'technology', title:'Review the ledger', createdAt:'', updatedAt:'', resultSummary:''}
];
w.receive({event:'taskUpdate', data:tasks});
w.receive({event:'work', data:{seat:'creative', taskID:'R1', phase:'handoff', title:'Create a thirty-second video', text:'On it', at:now, since:now}});
const creative = d.querySelector('.seat[data-seat="creative"]');
assert.ok(creative.classList.contains('working'));
assert.ok(d.querySelector('#voiceGrid .handoff-orb'), 'a hand-off orb flies from Jarvis');
assert.match(d.querySelector('.seat[data-seat="jarvis"] .bubble').textContent, /Creative, this one's yours/);
assert.match(creative.querySelector('.work-badge').textContent, /Working/);
assert.match(d.getElementById('boardStrip').textContent, /Creative/);
assert.ok(d.querySelector('#boardStrip .strip-seat.working'));
console.log('PASS: a hand-off flies from Jarvis to the director, who lights up as working on the board and the home strip');
w.receive({event:'videoProgress', data:{taskID:'R1', title:'Drop', renderer:'4090 · ComfyUI', stage:'rendering', headline:'Rendering shot 1 of 2 · diffusing 4/8', note:'free on the 4090', gpu:'NVIDIA GeForce RTX 4090 · 18.0 / 22.5 GB VRAM · 98% busy · 63 °C', percent:30, startedMs:now-60000, endedMs:null,
  shots:[{n:1, seconds:5, prompt:'Rooftop drop', state:'rendering', activity:'diffusing', step:4, steps:8, percent:45, startedMs:now-30000, endedMs:null, thumb:null, note:''},
         {n:2, seconds:5, prompt:'Street fight', state:'queued', activity:'', step:0, steps:0, percent:0, startedMs:null, endedMs:null, thumb:null, note:''}]}});
const card = d.querySelector('#taskPanel .studio[data-studio="R1"]');
assert.ok(card, 'the Studio card sits under the running video task');
assert.match(card.textContent, /diffusing 4\/8/);
assert.match(card.textContent, /RTX 4090/);
assert.equal(card.querySelectorAll('.shot').length, 2);
assert.ok(card.querySelector('.shot.rendering .spin'));
assert.ok(d.querySelector('#boardTasks .studio.compact'));
w.receive({event:'videoProgress', data:{taskID:'R1', title:'Drop', renderer:'4090 · ComfyUI', stage:'finished', headline:'Finished: Drop', note:'', gpu:'', percent:100, startedMs:now-60000, endedMs:now, shots:[]}});
const done = d.querySelector('#taskPanel .studio[data-studio="R1"]');
assert.ok(done.classList.contains('finished'));
done.querySelector('button[data-play]').click();
assert.deepEqual({...calls.at(-1)}, {action:'openResult', id:'P1'});
console.log('PASS: the Studio card shows each shot, the sampler step and the 4090 live, and plays the finished video');
w.receive({event:'usage', data:{day:'2026-11-12', today:{creative:{calls:2, input:3000, output:900, total:3900, models:{'claude-sonnet-5-5':{calls:2, input:3000, output:900}}}}, allTime:{creative:{calls:5, input:9000, output:2000, total:11000}}}});
creative.querySelector('.figure').click();
const live = creative.querySelector('.seat-live');
assert.ok(live, 'clicking a director opens its live panel');
assert.match(live.textContent, /Working/);
assert.match(live.textContent, /3\.9k/);
assert.match(live.textContent, /claude-sonnet-5-5/);
assert.match(live.textContent, /Drop Assassin/);
const cto = d.querySelector('.seat[data-seat="cto"]');
cto.querySelector('.figure').click();
assert.match(cto.querySelector('.seat-live').textContent, /Idle/);
assert.match(cto.querySelector('.seat-live').textContent, /Review the ledger/);
cto.querySelector('.seat-live button[data-open]').click();
assert.equal(calls.at(-1).action, 'openResult'); assert.equal(calls.at(-1).id, 'P0');
console.log("PASS: clicking a director shows what it is doing, its tasks with results, and its tokens by model");
w.receive({event:'work', data:{seat:'creative', taskID:'R1', phase:'done', title:'Create a thirty-second video', text:'Done', at:now}});
assert.equal(creative.classList.contains('working'), false);
assert.match(creative.querySelector('.bubble').textContent, /Done/);
w.receive({event:'resultReady', data:{key:'2026-11-12 Drop p1', title:'Drop Assassin', kind:'video', date:'2026-11-12'}});
const toast = d.getElementById('resultToast');
assert.ok(toast.classList.contains('show'));
toast.querySelector('.primary').click();
assert.deepEqual({...calls.at(-1)}, {action:'showResult', key:'2026-11-12 Drop p1'});
d.querySelector('nav button[data-view="results"]').click();
assert.equal(calls.at(-1).action, 'listResults');
w.receive({event:'results', data:[{key:'2026-11-12 Drop p1', title:'Drop Assassin', kind:'video', date:'2026-11-12', summary:'3 shots'}, {key:'2026-11-11 Plan p0', title:'Ledger review', kind:'document', date:'2026-11-11', summary:''}]});
assert.equal(d.querySelectorAll('#resultList .result-item').length, 2);
w.receive({event:'showResult', data:{key:'2026-11-12 Drop p1', title:'Drop Assassin', kind:'video', date:'2026-11-12', video:'jarvis-media://results/2026-11-12%20Drop%20p1/final.mp4', shots:['jarvis-media://results/a/shot-1.mp4','jarvis-media://results/a/shot-2.mp4'], text:'# Drop Assassin\n\n## Shots\n\n- **Shot 1** rooftop\n- Shot 2 <script>x</script>'}});
assert.ok(d.getElementById('results').classList.contains('active'));
const video = d.querySelector('#resultViewer video');
assert.equal(video.getAttribute('src'), 'jarvis-media://results/2026-11-12%20Drop%20p1/final.mp4');
assert.equal(d.querySelectorAll('#resultViewer .shot-picks button').length, 3);
assert.ok(d.querySelector('#resultViewer .md li b'));
assert.equal(d.querySelector('#resultViewer .md script'), null);
d.querySelector('#resultViewer [data-reveal]').click();
assert.equal(calls.at(-1).action, 'revealResult');
console.log('PASS: results open inside Jarvis: the video plays with shot picks, and the document reads safely');
d.getElementById('reloadUI').click();
assert.equal(calls.at(-1).action, 'reloadUI');
assert.match(d.querySelector('meta[http-equiv]').getAttribute('content'), /media-src[^;]*jarvis-media:/);
console.log('PASS: Settings can reload the UI from source, and the page may play result media');
w.close();
