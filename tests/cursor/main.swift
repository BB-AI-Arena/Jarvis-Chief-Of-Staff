import Foundation
assert(CursorClient.base == "https://api.cursor.com")
assert(CursorClient.defaultRepo == "https://github.com/BB-AI-Arena/Jarvis-Chief-Of-Staff")
assert(CursorClient.sanitizeModel("  ") == "")
assert(CursorClient.sanitizeModel(" composer-2 ") == "composer-2")
assert(CursorClient.sanitizeModel("bad model") == nil)
assert(CursorClient.sanitizeRepo("https://github.com/BB-AI-Arena/Jarvis-Chief-Of-Staff") != nil)
assert(CursorClient.sanitizeRepo("http://github.com/a/b") == nil)
assert(CursorClient.sanitizeRepo("https://user:pw@github.com/a/b") == nil)
assert(CursorClient.sanitizeRepo("https://github.com") == nil)
assert(CursorClient.agentLink("bc-1") == "https://cursor.com/agents/bc-1")
let prompt = CursorClient.prompt(persona: "PERSONA", brief: "Polish the boardroom")
assert(prompt.hasPrefix("PERSONA") && prompt.contains("Polish the boardroom"))
let body = CursorClient.launchBody(prompt: "p", repo: "https://github.com/a/b", model: "", name: "Creative")
assert(body["model"] == nil)
assert(((body["repos"] as? [[String: String]])?.first?["url"]) == "https://github.com/a/b")
assert((body["prompt"] as? [String: String])?["text"] == "p")
assert(((CursorClient.launchBody(prompt: "p", repo: "r", model: "composer-2", name: "n")["model"]) as? [String: String])?["id"] == "composer-2")
let launched = Data("{\"agent\":{\"id\":\"bc-1\",\"latestRunId\":\"run-1\"},\"run\":{\"id\":\"run-1\",\"status\":\"CREATING\"}}".utf8)
assert(CursorClient.parseLaunch(launched)?.agent == "bc-1" && CursorClient.parseLaunch(launched)?.run == "run-1")
assert(CursorClient.parseLaunch(Data("{\"error\":\"unauthorized\"}".utf8)) == nil)
let finished = Data("{\"status\":\"FINISHED\",\"result\":\"Done.\",\"git\":{\"branches\":[{\"repoUrl\":\"github.com/a/b\",\"prUrl\":\"https://github.com/a/b/pull/1\"}]}}".utf8)
let run = CursorClient.parseRun(finished)
assert(run?.status == "FINISHED" && run?.result == "Done." && run?.pr == "https://github.com/a/b/pull/1")
assert(CursorClient.terminal.contains("FINISHED") && CursorClient.terminal.contains("ERROR") && !CursorClient.terminal.contains("RUNNING"))
assert(CursorClient.parseRun(Data("{\"status\":\"RUNNING\"}".utf8))?.result == nil)
print("PASS: Cursor cloud agents launch with the persona brief on a validated https repo and read only documented run states")

let fullBrief = String(repeating:"a",count:25000) + "END_OF_OWNER_BRIEF"
assert(CursorClient.prompt(persona:"P",brief:fullBrief).contains(fullBrief))
print("PASS: Creative receives the complete long consultation brief without a silent cutoff")
