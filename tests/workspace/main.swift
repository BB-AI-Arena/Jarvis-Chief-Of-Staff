import Foundation
let base = FileManager.default.temporaryDirectory.appendingPathComponent("jarvis-tools-\(UUID().uuidString)")
let work = base.appendingPathComponent("work"), source = base.appendingPathComponent("src"), outside = base.appendingPathComponent("outside")
for dir in [work.appendingPathComponent("Results"), source.appendingPathComponent("Sources"), source.appendingPathComponent(".git"), source.appendingPathComponent("node_modules/x"), outside] { try! FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true) }
try! "# Plan\nShip Friday\n".write(to: work.appendingPathComponent("Results/plan.md"), atomically: true, encoding: .utf8)
try! "let answer = 42\nfunc ledger() {}\n".write(to: source.appendingPathComponent("Sources/main.swift"), atomically: true, encoding: .utf8)
try! "API_KEY=secret-value".write(to: source.appendingPathComponent(".env"), atomically: true, encoding: .utf8)
try! "token".write(to: source.appendingPathComponent("secrets.txt"), atomically: true, encoding: .utf8)
try! "ledger hidden".write(to: source.appendingPathComponent("node_modules/x/index.js"), atomically: true, encoding: .utf8)
try! "private".write(to: outside.appendingPathComponent("diary.txt"), atomically: true, encoding: .utf8)
let tools = WorkspaceTools(roots: ["workspace": work, "source": source])
assert(tools.list("") == "source/\nworkspace/")
assert(tools.list("workspace") == "Results/")
assert(tools.list("source") == "Sources/")
assert(tools.read("workspace/Results/plan.md", start: 1) == "1\t# Plan\n2\tShip Friday\n3\t")
assert(tools.read("source/Sources/main.swift", start: 2).hasPrefix("2\tfunc ledger() {}"))
for bad in ["../outside/diary.txt", "workspace/../../outside/diary.txt", "/etc/passwd", "source/.env", "source/secrets.txt", "source/.git", "source/node_modules/x/index.js", "elsewhere/file"] {
    assert(tools.resolve(bad) == nil, bad)
    assert(tools.read(bad, start: 1).contains("outside the readable areas"), bad)
}
try! FileManager.default.createSymbolicLink(at: work.appendingPathComponent("escape"), withDestinationURL: outside)
assert(tools.resolve("workspace/escape/diary.txt") == nil)
let found = tools.search("LEDGER")
assert(found == "source/Sources/main.swift:2: func ledger() {}")
assert(tools.search("secret-value").hasPrefix("No matches") && tools.search("private").hasPrefix("No matches"))
assert(tools.run("search_code", ["query": "Ship"]) == "workspace/Results/plan.md:2: Ship Friday")
assert(tools.run("delete_file", [:]).hasPrefix("Unknown tool"))
assert(WorkspaceTools.definitions.map { $0["name"] as! String } == ["list_files", "read_file", "search_code"])
try? FileManager.default.removeItem(at: base)
print("PASS: the CTO's tools are read-only, stay inside the workspace and source folders, and never expose secrets, hidden or dependency files")
