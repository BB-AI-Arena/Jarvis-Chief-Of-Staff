import Foundation
let plain = "{\"route\":\"task\",\"text\":\"Inspect the source without edits\"}"
assert(RouteDecision.decode(plain)?.route == "task")
assert(RouteDecision.decode("```json\n" + plain + "\n```")?.route == "task")
assert(RouteDecision.decode("```\n" + plain + "\n```")?.route == "task")
assert(RouteDecision.decode("text before " + plain) == nil)
assert(RouteDecision.decode("{\"route\":\"shell\",\"text\":\"bad route\"}") == nil)
assert(RouteDecision.decode("{\"route\":\"task\",\"text\":\"\"}") == nil)
let work = RouteDecision.decode(plain)!
let assigned = RouteDecision.assignment(for: work)
assert(assigned?.director == "operations")
assert(assigned?.director != "jarvis")
assert(RouteDecision.assignment(for: RouteDecision(route: "reply", text: "Hello", director: nil)) == nil)
assert(RouteDecision.assignment(for: RouteDecision(route: "astra", text: "Reason about this", director: nil)) == nil)
assert(RouteDecision.classify("Ask Grok to research the market", hinted: nil) == "research")
assert(RouteDecision.classify("Design a new mark", hinted: nil) == "creative")
assert(RouteDecision.classify("Draft a project plan", hinted: nil) == "projects")
assert(RouteDecision.classify("Claude, do an engineering review", hinted: nil) == "technology")
assert(RouteDecision.decode("{\"route\":\"assign\",\"director\":\"jarvis\",\"text\":\"Do it\"}") == nil)
assert(RouteDecision.decode("{\"route\":\"assign\",\"director\":\"research\",\"text\":\"Survey the field\"}")?.director == "research")
assert(OperationsManager.resolve(stored: nil, advertised: []) == nil)
assert(OperationsManager.resolve(stored: "GPT Sol 6.1", advertised: []) == nil)
assert(OperationsManager.resolve(stored: nil, advertised: ["gemma4:latest"]) == nil)
assert(OperationsManager.resolve(stored: nil, advertised: ["gpt-sol-6.1"]) == "gpt-sol-6.1")
assert(OperationsManager.resolve(stored: "gpt-6-astra", advertised: []) == "gpt-6-astra")
assert(OperationsManager.resolve(stored: "gpt-6-sol", advertised: []) == "gpt-6-sol")
assert(OperationsManager.worker(manager: "gpt-6-sol").model == "gpt-6-sol")
assert(OperationsManager.worker(manager: "gpt-6-sol").config == ["-c", "model_reasoning_effort=\"medium\""])
assert(OperationsManager.worker(manager: nil).model == "gpt-6-astra" && OperationsManager.worker(manager: nil).config.isEmpty)
assert(OperationsManager.worker(manager: "gemma4:latest").model == "gpt-6-astra")
print("PASS: plain and fenced routing accepted; malformed, unknown and empty instructions rejected")
print("PASS: Jarvis never executes; work is assigned to a director, and an unverified manager id stays unset")
let suggestion = RouteDecision.decode("{\"route\":\"suggest\",\"text\":\"Shall I add a launch plan for Projects?\",\"task\":\"Draft the launch plan\",\"director\":\"projects\"}")
assert(suggestion?.route == "suggest" && suggestion?.task == "Draft the launch plan")
assert(RouteDecision.assignment(for: suggestion!) == nil)
assert(RouteDecision.suggestion(for: suggestion!)?.director == "projects")
assert(RouteDecision.suggestion(for: suggestion!)?.title == "Draft the launch plan")
assert(RouteDecision.decode("{\"route\":\"suggest\",\"text\":\"Shall I?\"}") == nil)
assert(RouteDecision.suggestion(for: RouteDecision(route: "reply", text: "Hello", director: nil)) == nil)
print("PASS: a suggested task is never an assignment; it needs approval before it reaches the ledger")
let schema = RouteDecision.outputSchema
let properties = Set((schema["properties"] as! [String: Any]).keys)
assert(Set(schema["required"] as! [String]) == properties, "strict structured output requires every property")
assert(schema["additionalProperties"] as? Bool == false)
let nullAssign = RouteDecision.decode("{\"route\":\"assign\",\"text\":\"Draft a project plan for the handyman MVP\",\"director\":null,\"task\":null}")
assert(nullAssign != nil && RouteDecision.assignment(for: nullAssign!)?.director == "projects")
assert(RouteDecision.decode("{\"route\":\"reply\",\"text\":\"Certainly.\",\"director\":null,\"task\":null}")?.route == "reply")
assert(RouteDecision.decode("{\"route\":\"suggest\",\"text\":\"Shall I?\",\"director\":null,\"task\":null}") == nil)
print("PASS: Luna's routing schema is strict (every property required, optional ones nullable) and null directors fall back to classify")
assert(RouteDecision.routes.contains("debate"))
assert(((RouteDecision.outputSchema["properties"] as! [String: Any])["route"] as! [String: Any])["enum"] as! [String] == RouteDecision.routes)
let debate = RouteDecision.decode("{\"route\":\"debate\",\"text\":\"I'll put it to the board.\",\"director\":null,\"task\":\"Should we build the handyman app first?\"}")!
assert(RouteDecision.debateTopic(for: debate) == "Should we build the handyman app first?")
assert(RouteDecision.assignment(for: debate) == nil && RouteDecision.suggestion(for: debate) == nil)
let bare = RouteDecision.decode("{\"route\":\"debate\",\"text\":\"Ship this week?\",\"director\":null,\"task\":\"  \"}")!
assert(RouteDecision.debateTopic(for: bare) == "Ship this week?")
assert(RouteDecision.debateTopic(for: RouteDecision(route: "reply", text: "Hello", director: nil)) == nil)
assert(RouteDecision.debateRule.contains("route=debate") && RouteDecision.debateRule.contains("never invent"))
print("PASS: Jarvis can route a request to a board debate; the question comes from task, and debates are never assignments")
assert(RouteDecision.classify("Make a 30 second video about Drop Assassin", hinted: nil) == "creative")
assert(RouteDecision.routerRules.contains("director creative"))
print("PASS: video requests go to the Creative Director")
