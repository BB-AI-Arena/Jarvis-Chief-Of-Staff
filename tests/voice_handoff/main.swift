import Foundation
var h = VoiceHandoff()
let first = h.append("Create a ten second video", start: 100)
assert(h.append(" based on Drop Assassin artwork", start: 500) == first)
assert(h.close() == first)
assert(h.claim(first) == "Create a ten second video based on Drop Assassin artwork")
assert(h.claim(first) == nil, "A late server delegation must not duplicate the fallback")
let second = h.append("Make it twenty seconds instead", start: 2000)
assert(second != first && h.turn(at: 1500) == first)
assert(h.claim(h.turn(at: 1500)!) == nil, "Late delegation must not consume the newer turn")
assert(h.claim(second) == "Make it twenty seconds instead")
assert(h.close() == second)
assert(h.claim(second) == nil, "Explicit delegation followed by assistant output must run once")
let third = h.append("Hello Jarvis", start: nil)
assert(h.turn(at: nil) == third)
assert(h.close() == third && h.claim(third) == "Hello Jarvis")
var empty = VoiceHandoff()
assert(empty.close() == nil && empty.turn(at: nil) == nil)
print("PASS: voice requests route without a model hand-off, retain transcript fragments, and deduplicate delayed delegations across turns")
